import XCTest
@testable import ClipCore

final class ClassifierTests: XCTestCase {
    func testMarkerTypesAreSkipped() {
        XCTAssertEqual(
            PasteboardTypeClassifier.classify(types: [ClipUTI.utf8PlainText, ClipUTI.concealed], string: "hunter2"),
            .skip(.concealed)
        )
        XCTAssertEqual(
            PasteboardTypeClassifier.classify(types: [ClipUTI.transient, ClipUTI.utf8PlainText], string: "x"),
            .skip(.transient)
        )
        XCTAssertEqual(
            PasteboardTypeClassifier.classify(types: [ClipUTI.autoGenerated, ClipUTI.png], string: nil),
            .skip(.autoGenerated)
        )
        XCTAssertEqual(
            PasteboardTypeClassifier.classify(types: ["com.agilebits.onepassword", ClipUTI.utf8PlainText], string: "pw"),
            .skip(.ignoredType)
        )
        XCTAssertEqual(PasteboardTypeClassifier.classify(types: [], string: nil), .skip(.empty))
        XCTAssertEqual(PasteboardTypeClassifier.classify(types: ["com.example.private"], string: nil), .skip(.unsupported))
        XCTAssertTrue(PasteboardTypeClassifier.classify(types: [ClipUTI.concealed], string: nil).isSkipped)
    }

    func testSourceMarkerIsNotASkip() {
        XCTAssertEqual(
            PasteboardTypeClassifier.classify(types: [ClipUTI.source, ClipUTI.utf8PlainText], string: "hello"),
            .kind(.text)
        )
    }

    func testKinds() {
        XCTAssertEqual(PasteboardTypeClassifier.classify(types: [ClipUTI.utf8PlainText], string: "hello world").kind, .text)
        XCTAssertEqual(PasteboardTypeClassifier.classify(types: [ClipUTI.utf8PlainText, ClipUTI.rtf], string: "Bold").kind, .richText)
        XCTAssertEqual(PasteboardTypeClassifier.classify(types: [ClipUTI.utf8PlainText], string: "https://example.com/a?b=1").kind, .link)
        XCTAssertEqual(PasteboardTypeClassifier.classify(types: [ClipUTI.url, ClipUTI.utf8PlainText, ClipUTI.rtf], string: "https://apple.com").kind, .link)
        XCTAssertEqual(PasteboardTypeClassifier.classify(types: [ClipUTI.url], string: nil).kind, .link)
        XCTAssertEqual(PasteboardTypeClassifier.classify(types: [ClipUTI.utf8PlainText], string: "#1e90ff").kind, .color)
        XCTAssertEqual(PasteboardTypeClassifier.classify(types: [ClipUTI.utf8PlainText], string: "rgb(30, 144, 255)").kind, .color)
        XCTAssertEqual(PasteboardTypeClassifier.classify(types: [ClipUTI.png, ClipUTI.tiff], string: nil).kind, .image)
        XCTAssertEqual(PasteboardTypeClassifier.classify(types: [ClipUTI.pdf, ClipUTI.tiff], string: nil).kind, .pdf)
        XCTAssertEqual(PasteboardTypeClassifier.classify(types: [ClipUTI.fileURL, ClipUTI.tiff], string: "file:///tmp/a.png").kind, .file)
        XCTAssertEqual(PasteboardTypeClassifier.classify(types: [ClipUTI.color], string: nil).kind, .color)
        // Word-style payload: text + rtf + pdf + png is rich text, not an image.
        XCTAssertEqual(
            PasteboardTypeClassifier.classify(types: [ClipUTI.utf8PlainText, ClipUTI.rtf, ClipUTI.pdf, ClipUTI.png], string: "Quarterly").kind,
            .richText
        )
    }

    func testLegacyTypeNamesAreNormalized() {
        XCTAssertEqual(TypeNormalizer.normalize("NSStringPboardType"), ClipUTI.utf8PlainText)
        XCTAssertEqual(TypeNormalizer.normalize("Apple PNG pasteboard type"), ClipUTI.png)
        XCTAssertEqual(TypeNormalizer.normalize("public.jpeg"), "public.jpeg")
        XCTAssertEqual(
            TypeNormalizer.normalize(["NSStringPboardType", ClipUTI.utf8PlainText, "", "NeXT TIFF v4.0 pasteboard type"]),
            [ClipUTI.utf8PlainText, ClipUTI.tiff]
        )
        XCTAssertEqual(PasteboardTypeClassifier.classify(types: ["NeXT TIFF v4.0 pasteboard type"], string: nil).kind, .image)
    }

    func testRepresentationNormalizationFiltersAndDedupes() {
        let reps = [
            ClipDraft.Representation(uti: "NSStringPboardType", data: Data("a".utf8)),
            ClipDraft.Representation(uti: ClipUTI.utf8PlainText, data: Data("b".utf8)),
            ClipDraft.Representation(uti: "dyn.ah62d4rv4gu8y", data: Data("c".utf8)),
            ClipDraft.Representation(uti: ClipUTI.source, data: Data("com.apple.Safari".utf8)),
            ClipDraft.Representation(uti: ClipUTI.png, data: Data())
        ]
        let normalized = TypeNormalizer.normalizeRepresentations(reps)
        XCTAssertEqual(normalized.count, 1)
        XCTAssertEqual(normalized.first?.uti, ClipUTI.utf8PlainText)
        XCTAssertEqual(normalized.first?.data, Data("a".utf8))
    }

    func testLinkDetection() {
        XCTAssertTrue(PasteboardTypeClassifier.isLink("http://example.com"))
        XCTAssertTrue(PasteboardTypeClassifier.isLink("  https://example.com/path  "))
        XCTAssertTrue(PasteboardTypeClassifier.isLink("mailto:someone@example.com"))
        XCTAssertFalse(PasteboardTypeClassifier.isLink("example.com"))
        XCTAssertFalse(PasteboardTypeClassifier.isLink("see https://example.com now"))
        XCTAssertFalse(PasteboardTypeClassifier.isLink("file:///etc/hosts"))
        XCTAssertFalse(PasteboardTypeClassifier.isLink(""))
    }

    func testColorParsing() {
        XCTAssertEqual(ColorParser.normalizedHex(from: "#fff"), "#FFFFFF")
        XCTAssertEqual(ColorParser.normalizedHex(from: " #1e90ff "), "#1E90FF")
        XCTAssertEqual(ColorParser.normalizedHex(from: "#1E90FF80"), "#1E90FF80")
        XCTAssertEqual(ColorParser.normalizedHex(from: "rgb(255, 0, 16)"), "#FF0010")
        XCTAssertEqual(ColorParser.normalizedHex(from: "RGBA(0,0,0,1)"), "#000000FF")
        XCTAssertNil(ColorParser.normalizedHex(from: "facade"))
        XCTAssertNil(ColorParser.normalizedHex(from: "#12345"))
        XCTAssertNil(ColorParser.normalizedHex(from: "rgb(300, 0, 0)"))
        let components = ColorParser.components(fromHex: "#FF0000")
        XCTAssertEqual(components?.red ?? -1, 1.0, accuracy: 0.0001)
        XCTAssertEqual(components?.green ?? -1, 0.0, accuracy: 0.0001)
        XCTAssertEqual(components?.alpha ?? -1, 1.0, accuracy: 0.0001)
    }
}

final class HasherTests: XCTestCase {
    func testKnownSHA256Vector() {
        XCTAssertEqual(
            ContentHasher.sha256Hex("abc"),
            "ba7816bf8f01cfea414140de5dae2223b00361a396177a9cb410ff61f20015ad"
        )
    }

    func testTextHashIsNormalized() {
        let a = ContentHasher.hash(kind: .text, plainText: "line1\r\nline2", representations: [])
        let b = ContentHasher.hash(kind: .text, plainText: "line1\nline2\n", representations: [])
        let c = ContentHasher.hash(kind: .richText, plainText: "  line1\nline2", representations: [])
        let d = ContentHasher.hash(kind: .text, plainText: "line1 line2", representations: [])
        XCTAssertEqual(a, b)
        XCTAssertEqual(a, c, "plain and rich copies of the same text dedup")
        XCTAssertNotEqual(a, d)
        XCTAssertEqual(a.count, 64)
    }

    func testBinaryHashIgnoresRepresentationOrderAndInternalTypes() {
        let png = ClipDraft.Representation(uti: ClipUTI.png, data: Data([1, 2, 3]))
        let tiff = ClipDraft.Representation(uti: ClipUTI.tiff, data: Data([4, 5, 6]))
        let thumb = ClipDraft.Representation(uti: ClipUTI.thumbnail, data: Data([9]))
        let h1 = ContentHasher.hash(kind: .image, plainText: nil, representations: [png, tiff])
        let h2 = ContentHasher.hash(kind: .image, plainText: nil, representations: [tiff, png, thumb])
        let h3 = ContentHasher.hash(kind: .image, plainText: nil, representations: [png])
        XCTAssertEqual(h1, h2)
        XCTAssertNotEqual(h1, h3)
    }
}

final class IgnoreRulesTests: XCTestCase {
    func testDefaultsIgnorePasswordManagers() {
        let rules = IgnoreRules()
        XCTAssertTrue(rules.shouldIgnore(bundleID: "com.1password.1password"))
        XCTAssertTrue(rules.shouldIgnore(bundleID: "com.agilebits.onepassword7"))
        XCTAssertTrue(rules.shouldIgnore(bundleID: "com.1password.browser-helper"), "prefix rule")
        XCTAssertTrue(rules.shouldIgnore(bundleID: "com.bitwarden.desktop"))
        XCTAssertTrue(rules.shouldIgnore(bundleID: "COM.APPLE.KEYCHAINACCESS"), "case-insensitive")
        XCTAssertFalse(rules.shouldIgnore(bundleID: "com.apple.Safari"))
        XCTAssertFalse(rules.shouldIgnore(bundleID: nil))
        XCTAssertFalse(rules.shouldIgnore(bundleID: "com.1passwordx"), "prefix rule needs the dot")
    }

    func testUserRulesAndCodable() throws {
        var rules = IgnoreRules()
        rules.add("com.tinyspeck.slackmacgap")
        rules.add("COM.TINYSPECK.SLACKMACGAP")
        XCTAssertEqual(rules.userBundleIDs.count, 1)
        XCTAssertTrue(rules.shouldIgnore(bundleID: "com.tinyspeck.slackmacgap"))

        let data = try JSONEncoder().encode(rules)
        let decoded = try JSONDecoder().decode(IgnoreRules.self, from: data)
        XCTAssertEqual(decoded, rules)

        rules.remove("com.tinyspeck.slackmacgap")
        XCTAssertFalse(rules.shouldIgnore(bundleID: "com.tinyspeck.slackmacgap"))

        let userOnly = IgnoreRules(userBundleIDs: ["com.example.app"], includeDefaults: false)
        XCTAssertFalse(userOnly.shouldIgnore(bundleID: "com.1password.1password"))
        XCTAssertTrue(userOnly.shouldIgnore(bundleID: "com.example.app"))
    }
}

final class RetentionPolicyTests: XCTestCase {
    func testCutoffs() {
        let now = Date(timeIntervalSince1970: 1_700_000_000)
        var calendar = Calendar(identifier: .gregorian)
        calendar.timeZone = TimeZone(identifier: "UTC") ?? TimeZone.current
        XCTAssertNil(RetentionPolicy.forever.cutoffDate(from: now, calendar: calendar))
        XCTAssertEqual(RetentionPolicy.day.cutoffDate(from: now, calendar: calendar), now.addingTimeInterval(-86_400))
        XCTAssertEqual(RetentionPolicy.week.cutoffDate(from: now, calendar: calendar), now.addingTimeInterval(-7 * 86_400))
        let month = RetentionPolicy.month.cutoffDate(from: now, calendar: calendar)
        XCTAssertNotNil(month)
        XCTAssertLessThan(month ?? now, now)
    }
}

final class SearchEngineTests: XCTestCase {
    func testNormalizationAndTokens() {
        XCTAssertEqual(SearchEngine.normalize("Café ÜBER"), "cafe uber")
        XCTAssertEqual(SearchEngine.tokens(from: "  Crème   brûlée crème "), ["creme", "brulee"])
        XCTAssertEqual(SearchEngine.tokens(from: "   "), [])
    }

    func testMultiTokenAndSemantics() {
        let text = SearchEngine.makeSearchText(title: "Invoice", plainText: "Total: 42 €", ocrText: "Résumé", sourceAppName: "Mail")
        XCTAssertTrue(SearchEngine.matches(searchText: text, tokens: SearchEngine.tokens(from: "invoice mail")))
        XCTAssertTrue(SearchEngine.matches(searchText: text, tokens: SearchEngine.tokens(from: "RESUME")))
        XCTAssertFalse(SearchEngine.matches(searchText: text, tokens: SearchEngine.tokens(from: "invoice safari")))
        XCTAssertTrue(SearchEngine.matches(searchText: text, tokens: []))
    }
}
