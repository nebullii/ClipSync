import Foundation

/// Maps legacy pasteboard type names to modern UTIs and filters what is worth storing.
public enum TypeNormalizer {
    /// Legacy NSPasteboard names (pre-UTI) → modern UTI.
    public static let legacyMap: [String: String] = [
        "NSStringPboardType": ClipUTI.utf8PlainText,
        "NeXT plain ascii pasteboard type": ClipUTI.utf8PlainText,
        "NeXT Rich Text Format v1.0 pasteboard type": ClipUTI.rtf,
        "NeXT RTFD pasteboard type": ClipUTI.rtfd,
        "Apple HTML pasteboard type": ClipUTI.html,
        "Apple PNG pasteboard type": ClipUTI.png,
        "NeXT TIFF v4.0 pasteboard type": ClipUTI.tiff,
        "Apple PDF pasteboard type": ClipUTI.pdf,
        "Apple URL pasteboard type": ClipUTI.url,
        "NSFilenamesPboardType": ClipUTI.fileURL,
        "NSColor pasteboard type": ClipUTI.color
    ]

    /// Modern UTI for a single type string (unknown types pass through unchanged).
    public static func normalize(_ type: String) -> String {
        let trimmed = type.trimmingCharacters(in: .whitespacesAndNewlines)
        if let mapped = legacyMap[trimmed] {
            return mapped
        }
        return trimmed
    }

    /// Normalizes every type, drops empties, removes duplicates keeping first-seen order.
    public static func normalize(_ types: [String]) -> [String] {
        var seen = Set<String>()
        var result: [String] = []
        for type in types {
            let normalized = normalize(type)
            if normalized.isEmpty { continue }
            if seen.insert(normalized).inserted {
                result.append(normalized)
            }
        }
        return result
    }

    /// True for marker types (concealed/transient/auto-generated/legacy skip markers).
    public static func isMarker(_ type: String) -> Bool {
        return type == ClipUTI.concealed
            || type == ClipUTI.transient
            || type == ClipUTI.autoGenerated
            || ClipUTI.legacySkipTypes.contains(type)
    }

    /// True when a representation of this (normalized) type should be persisted.
    /// Rejects markers, `org.nspasteboard.source`, `ClipUTI.ownWrite`, dynamic `dyn.*` types
    /// and empty strings. (`ClipUTI.fileURLList` IS storable: it is an internal representation.)
    public static func isStorable(_ type: String) -> Bool {
        if type.isEmpty { return false }
        if isMarker(type) { return false }
        if type == ClipUTI.source { return false }
        if type == ClipUTI.ownWrite { return false }   // ClipSync's own pasteboard marker
        if type.hasPrefix("dyn.") { return false }
        return true
    }

    /// Normalizes UTIs, drops non-storable types and empty payloads, keeps the first
    /// representation per UTI, preserving order.
    public static func normalizeRepresentations(_ representations: [ClipDraft.Representation]) -> [ClipDraft.Representation] {
        var seen = Set<String>()
        var result: [ClipDraft.Representation] = []
        for rep in representations {
            let uti = normalize(rep.uti)
            guard isStorable(uti), !rep.data.isEmpty else { continue }
            if seen.insert(uti).inserted {
                result.append(ClipDraft.Representation(uti: uti, data: rep.data))
            }
        }
        return result
    }
}
