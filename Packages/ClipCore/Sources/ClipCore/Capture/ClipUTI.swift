import Foundation

/// Uniform type identifier strings used across capture, storage and paste.
/// Plain strings (not `UTType`) so this file is usable everywhere without UniformTypeIdentifiers.
public enum ClipUTI {
    // Text
    public static let utf8PlainText = "public.utf8-plain-text"
    public static let utf16PlainText = "public.utf16-plain-text"
    public static let utf16ExternalPlainText = "public.utf16-external-plain-text"
    public static let plainText = "public.plain-text"
    public static let text = "public.text"
    // Rich text
    public static let rtf = "public.rtf"
    public static let rtfd = "com.apple.flat-rtfd"
    public static let html = "public.html"
    // Links / files
    public static let url = "public.url"
    public static let fileURL = "public.file-url"
    // Images
    public static let png = "public.png"
    public static let tiff = "public.tiff"
    public static let jpeg = "public.jpeg"
    public static let heic = "public.heic"
    public static let gif = "com.compuserve.gif"
    public static let image = "public.image"
    public static let webp = "org.webmproject.webp"
    // Documents / colors
    public static let pdf = "com.adobe.pdf"
    public static let color = "com.apple.cocoa.pasteboard.color"

    // nspasteboard.org markers (http://nspasteboard.org)
    public static let concealed = "org.nspasteboard.ConcealedType"
    public static let transient = "org.nspasteboard.TransientType"
    public static let autoGenerated = "org.nspasteboard.AutoGeneratedType"
    /// Carries the source app's bundle ID as its string value. NOT a skip marker.
    public static let source = "org.nspasteboard.source"

    /// Older / vendor-specific markers that also mean "do not record".
    public static let legacySkipTypes: Set<String> = [
        "de.petermaurer.TransientPasteboardType",
        "com.typeit4me.clipping",
        "Pasteboard generator type",
        "com.agilebits.onepassword",
        "net.antelle.keeweb"
    ]

    /// Prefix of ClipSync-private representation types (never pasted to other apps).
    public static let internalPrefix = "com.thingbits.clipsync."
    /// PNG thumbnail generated by the Media layer.
    public static let thumbnail = "com.thingbits.clipsync.thumbnail"
    /// Link favicon/icon image data fetched by the Media layer.
    public static let linkIcon = "com.thingbits.clipsync.link-icon"
    /// Link preview image data fetched by the Media layer.
    public static let linkPreviewImage = "com.thingbits.clipsync.link-image"
    /// Internal representation of a `.file` item holding EVERY copied file URL, in the
    /// format of `ClipFileList.encode(_:)` (UTF-8, one absolute `file://` URL per line).
    /// Written by the Mac clipboard monitor when more than one file was copied. Internal
    /// prefix → never pasted, not part of the content hash. Read with `store.fileURLs(for:)`.
    public static let fileURLList = "com.thingbits.clipsync.file-url-list"
    /// Pasteboard marker type ClipSync adds to everything it writes itself, so its own
    /// clipboard monitor never re-captures it. Never stored as a representation.
    public static let ownWrite = "com.thingbits.clipsync.own-write"

    public static let textTypes: Set<String> = [
        utf8PlainText, utf16PlainText, utf16ExternalPlainText, plainText, text
    ]
    public static let richTextTypes: Set<String> = [rtf, rtfd, html, "com.apple.rtfd"]
    public static let imageTypes: Set<String> = [png, tiff, jpeg, heic, gif, image, webp, "public.heif", "com.microsoft.bmp"]

    public static func isInternal(_ uti: String) -> Bool {
        return uti.hasPrefix(internalPrefix)
    }

    public static func isImage(_ uti: String) -> Bool {
        return imageTypes.contains(uti)
    }

    public static func isText(_ uti: String) -> Bool {
        return textTypes.contains(uti)
    }

    public static func isRichText(_ uti: String) -> Bool {
        return richTextTypes.contains(uti)
    }
}
